"""
Data models for LLM Socratic Evaluation and Question Generation.
"""
from typing import List, Optional, Literal
from pydantic import BaseModel, Field

from app.models.concept import KnowledgeChunk, Misconception


class LLMEvaluationRequest(BaseModel):
    """Input payload provided to the LLM Socratic Evaluator."""
    concept_id: str
    concept_title: str
    question: str
    student_response: str
    reference_chunks: List[KnowledgeChunk] = Field(default_factory=list)
    misconception_catalog: List[Misconception] = Field(default_factory=list)
    student_preference: str = Field(
        default="analogy_heavy",
        description="Learning style: analogy_heavy, code_centric, or step_by_step"
    )


class LLMEvaluationResponse(BaseModel):
    """Structured output expected from the LLM Socratic Evaluator."""
    is_correct: bool = Field(..., description="Whether the answer demonstrates conceptual mastery")
    score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Continuous assessment score in [0.0, 1.0]"
    )
    detected_misconceptions: List[str] = Field(
        default_factory=list,
        description="IDs of detected misconceptions matching the concept's catalog"
    )
    diagnosis: str = Field(
        ...,
        description="Pedagogical diagnosis of what the student understood vs what was confused"
    )
    feedback: str = Field(
        ...,
        description="Socratic response directly addressing the student"
    )
    step_by_step_explanation: str = Field(
        ...,
        description="Clear explanation of the underlying mechanics"
    )
    cited_chunk_ids: List[str] = Field(
        default_factory=list,
        description="IDs of reference knowledge chunks cited in this pedagogical explanation"
    )
    follow_up_challenge: Optional[str] = Field(
        default=None,
        description="A targeted transfer question or challenge to verify understanding"
    )
    canonical_answer: Optional[str] = Field(
        default="",
        description="Canonical correct solution or mechanism explanation"
    )
    evaluator_mode: Literal["llm_direct", "llm_rag_grounded", "rule_fallback", "mock"] = "llm_rag_grounded"
    confidence_score: float = Field(default=1.0, ge=0.0, le=1.0)


class GeneratedTransferQuestion(BaseModel):
    """A fresh question dynamically generated by the LLM for transfer learning."""
    concept_id: str
    prompt: str
    tip: Optional[str] = None
    expected_answer: str
    explanation: str
    target_misconception_id: Optional[str] = None
